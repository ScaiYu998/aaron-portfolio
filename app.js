function setLanguage(language) {
  const selected = translations[language] ? language : 'en';
  currentLanguage = selected;
  document.documentElement.lang = selected === 'zh' ? 'zh-CN' : 'en';
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = translations[selected][element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });
  languageOptions.forEach((option) => {
    const active = option.dataset.language === selected;
    option.classList.toggle('is-active', active);
    option.setAttribute('aria-current', active ? 'true' : 'false');
  });
  languageButton.setAttribute('aria-label', translations[selected][selected === 'en' ? 'switchToChinese' : 'switchToEnglish']);
  nav.setAttribute('aria-label', translations[selected].navAria);
  menuButton.setAttribute('aria-label', menuButton.getAttribute('aria-expanded') === 'true' ? translations[selected].closeNavigation : translations[selected].openNavigation);
  fieldLabel.textContent = hero.dataset.field === 'daylight' ? translations[selected].fieldDay : translations[selected].fieldNight;
  fieldButton.setAttribute('aria-label', hero.dataset.field === 'daylight' ? translations[selected].nightMapLabel : translations[selected].dayMapLabel);
  document.querySelector('.dialog-close').setAttribute('aria-label', translations[selected].closeProjectDetails);
  if (projectDialog.open && projectDialog.dataset.project) renderProjectDetails(projectDialog.dataset.project);
  try { localStorage.setItem('aaron-site-language', selected); } catch (_) { /* Storage may be disabled. */ }
  document.dispatchEvent(new Event('languagechange'));
}

