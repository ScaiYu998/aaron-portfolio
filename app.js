function elevation(x, y, time) {
  const shiftX = pointerX * .075;
  const shiftY = pointerY * .075;
  const a = x + shiftX;
  const b = y + shiftY;
  const wave = Math.sin(a * 6.4 + Math.sin(b * 3.7 + time) * 1.4) * .62
    + Math.cos(b * 8.2 - a * 1.7 + time * .32) * .34
    + Math.sin((a + b) * 5.1 + Math.cos(a * 3.2 - time * .2)) * .2;
  const hillOne = Math.exp(-(((a - .72) ** 2) * 8 + ((b - .35) ** 2) * 13)) * .7;
  const hillTwo = Math.exp(-(((a - .43) ** 2) * 15 + ((b - .7) ** 2) * 10)) * .45;
  return wave + hillOne + hillTwo;
}

function paintTerrain(timestamp = 0) {
  if (!canvasWidth || !canvasHeight) return;
  if (!reducedMotion.matches && timestamp - lastPaint < 32) {
    frame = requestAnimationFrame(paintTerrain);
    return;
  }
  lastPaint = timestamp;
  pointerX += (targetX - pointerX) * .025;
  pointerY += (targetY - pointerY) * .025;
  const time = reducedMotion.matches ? 0 : timestamp * .00012;
  const cols = Math.max(52, Math.min(104, Math.round(canvasWidth / 15)));
  const rows = Math.max(36, Math.min(70, Math.round(canvasHeight / 14)));
  const values = Array.from({ length: rows + 1 }, (_, row) => Array.from({ length: cols + 1 }, (_, col) => elevation(col / cols, row / rows, time)));
  const cellWidth = canvasWidth / cols;
  const cellHeight = canvasHeight / rows;
  const thresholds = [-.95, -.79, -.63, -.47, -.31, -.15, .01, .17, .33, .49, .65, .81, .97];

  context.clearRect(0, 0, canvasWidth, canvasHeight);
  const daylight = hero.dataset.field === 'daylight';
  context.beginPath();
  for (let column = 1; column < 10; column += 1) {
    const x = (canvasWidth / 10) * column;
    context.moveTo(x, 0);
    context.lineTo(x, canvasHeight);
  }
  for (let row = 1; row < 7; row += 1) {
    const y = (canvasHeight / 7) * row;
    context.moveTo(0, y);
    context.lineTo(canvasWidth, y);
  }
  context.lineWidth = .7;
  context.strokeStyle = daylight ? 'rgba(28,93,105,.12)' : 'rgba(108,174,205,.14)';
  context.stroke();

  context.lineWidth = 0.8;
  thresholds.forEach((threshold, levelIndex) => {
    context.beginPath();
    for (let row = 0; row < rows; row += 1) {
      for (let col = 0; col < cols; col += 1) {
        const topLeft = values[row][col];
        const topRight = values[row][col + 1];
        const bottomRight = values[row + 1][col + 1];
        const bottomLeft = values[row + 1][col];
        const cellCase = (topLeft >= threshold ? 1 : 0)
          | (topRight >= threshold ? 2 : 0)
          | (bottomRight >= threshold ? 4 : 0)
          | (bottomLeft >= threshold ? 8 : 0);
        if (cellCase === 0 || cellCase === 15) continue;

        const topRatio = (threshold - topLeft) / (topRight - topLeft);
        const rightRatio = (threshold - topRight) / (bottomRight - topRight);
        const bottomRatio = (threshold - bottomLeft) / (bottomRight - bottomLeft);
        const leftRatio = (threshold - topLeft) / (bottomLeft - topLeft);
        const leftX = col * cellWidth;
        const topY = row * cellHeight;
        const emit = (edgeA, edgeB) => {
          let ax; let ay; let bx; let by;
          if (edgeA === 0) { ax = leftX + topRatio * cellWidth; ay = topY; }
          else if (edgeA === 1) { ax = leftX + cellWidth; ay = topY + rightRatio * cellHeight; }
          else if (edgeA === 2) { ax = leftX + bottomRatio * cellWidth; ay = topY + cellHeight; }
          else { ax = leftX; ay = topY + leftRatio * cellHeight; }
          if (edgeB === 0) { bx = leftX + topRatio * cellWidth; by = topY; }
          else if (edgeB === 1) { bx = leftX + cellWidth; by = topY + rightRatio * cellHeight; }
          else if (edgeB === 2) { bx = leftX + bottomRatio * cellWidth; by = topY + cellHeight; }
          else { bx = leftX; by = topY + leftRatio * cellHeight; }
          context.moveTo(ax, ay);
          context.lineTo(bx, by);
        };

        switch (cellCase) {
          case 1: case 14: emit(3, 0); break;
          case 2: case 13: emit(0, 1); break;
          case 3: case 12: emit(3, 1); break;
          case 4: emit(1, 2); break;
          case 11: emit(1, 2); break;
          case 5: emit(3, 2); emit(0, 1); break;
          case 6: case 9: emit(0, 2); break;
          case 7: case 8: emit(3, 2); break;
          case 10: emit(0, 3); emit(1, 2); break;
        }
      }
    }
    const isAccent = levelIndex === 2 || levelIndex === 9 || levelIndex === 12;
    context.strokeStyle = daylight
      ? (isAccent ? 'rgba(8,127,152,.62)' : `rgba(28,105,123,${.20 + (levelIndex % 4) * .035})`)
      : (isAccent ? 'rgba(73,201,238,.72)' : `rgba(79,164,200,${.22 + (levelIndex % 4) * .035})`);
    context.lineWidth = isAccent ? 1.35 : .8;
    context.shadowBlur = !daylight && isAccent ? 5 : 0;
    context.shadowColor = 'rgba(73,210,239,.38)';
    context.stroke();
    context.shadowBlur = 0;
  });

  const focusX = canvasWidth * (.72 - pointerX * .09);
  const focusY = canvasHeight * (.48 - pointerY * .09);
  context.beginPath();
  context.arc(focusX, focusY, 2, 0, Math.PI * 2);
  context.fillStyle = daylight ? 'rgba(8,127,152,.95)' : 'rgba(73,201,238,.98)';
  context.fill();
  context.beginPath();
  context.arc(focusX, focusY, 13 + Math.sin(time * 4) * 2, 0, Math.PI * 2);
  context.strokeStyle = daylight ? 'rgba(8,127,152,.5)' : 'rgba(73,201,238,.55)';
  context.lineWidth = 1;
  context.stroke();

  context.save();
  context.strokeStyle = daylight ? 'rgba(8,127,152,.22)' : 'rgba(104,222,240,.3)';
  context.lineWidth = 1;
  context.setLineDash([3, 7]);
  context.beginPath();
  context.arc(focusX, focusY, Math.min(canvasWidth * .2, 210), 0, Math.PI * 2);
  context.stroke();
  context.setLineDash([]);
  const scanAngle = reducedMotion.matches ? -.7 : timestamp * .00016;
  const scanRadius = Math.min(canvasWidth * .2, 210);
  context.beginPath();
  context.moveTo(focusX, focusY);
  context.lineTo(focusX + Math.cos(scanAngle) * scanRadius, focusY + Math.sin(scanAngle) * scanRadius);
  context.stroke();
  context.fillStyle = daylight ? '#087f98' : '#ff8968';
  context.beginPath();
  context.arc(focusX + Math.cos(scanAngle) * scanRadius, focusY + Math.sin(scanAngle) * scanRadius, 3, 0, Math.PI * 2);
  context.fill();
  context.restore();

  if (!reducedMotion.matches) frame = requestAnimationFrame(paintTerrain);
}

function resizeTerrain() {
  const bounds = canvas.getBoundingClientRect();
  const ratio = Math.min(window.devicePixelRatio || 1, 1.5);
  canvasWidth = bounds.width;
  canvasHeight = bounds.height;
  canvas.width = Math.round(canvasWidth * ratio);
  canvas.height = Math.round(canvasHeight * ratio);
  context.setTransform(ratio, 0, 0, ratio, 0, 0);
  cancelAnimationFrame(frame);
  paintTerrain();
}

